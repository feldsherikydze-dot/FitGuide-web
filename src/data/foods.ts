export interface FoodPortion {
  kcal: number;
  p: number;
  f: number;
  c: number;
}

/** КБЖУ на порцию в граммах. */
export function foodPortion(food: Food, grams: number): FoodPortion {
  const k = Math.max(0, grams) / 100;
  return {
    kcal: Math.round(food.kcal * k),
    p: Math.round(food.p * k * 10) / 10,
    f: Math.round(food.f * k * 10) / 10,
    c: Math.round(food.c * k * 10) / 10,
  };
}

/** Поиск по названию; пустой запрос — вся база. */
export function searchFoods(query: string): Food[] {
  const q = (query || '').trim().toLowerCase();
  if (!q) return FOODS;
  return FOODS.filter(f => f.name.toLowerCase().includes(q));
}

export function foodsByCategory(cat: string): Food[] {
  return FOODS.filter(f => f.cat === cat);
}
