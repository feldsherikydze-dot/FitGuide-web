// FitGuide — единая таблица норм недельного объёма.
//
// Одна и та же норма используется тремя местами: генератором (цель объёма),
// разбором плана (PlanAdvisor) и анализом тренировок (WorkAnalysis). Раньше
// таблицы жили отдельно и расходились: план говорил «сбалансирован», а анализ
// после тренировки — «недобрал». Аудит 1.69, D-01.

import { GOALS, normalizeGoal } from './goals';

/**
 * Базовые недельные нормы объёма для гипертрофии, подходов на мышцу.
 * Одна норма на все группы не работает: ромбовидные живут за счёт тяг на
 * широчайшие, а плечи — за счёт жимов, и нижняя граница 6 давала им ложный
 * флаг «мало» на собственных программах приложения. Потолок «Плечи» 16 —
 * передняя дельта и так добирает от груди.
 */
export const BASE_VOLUME_NORMS: Record<string, [number, number]> = {
  'Грудь': [10, 20],
  'Широчайшие': [12, 20],
  'Квадрицепс': [10, 20],
  'Бицепс бедра': [8, 16],
  'Ягодицы': [8, 16],
  'Плечи': [6, 16],
  'Бицепс': [6, 12],
  'Трицепс': [6, 12],
  'Икры': [6, 12],
  'Пресс': [6, 12],
  'Трапеции': [4, 12],
  'Поясница': [3, 10],
  'Предплечья': [4, 12],
  'Приводящие': [4, 12],
  'Шея': [2, 8],
  'Ромбовидные': [2, 10],
};

/**
 * Норма недельного объёма под цель и уровень, {lo, hi}.
 *
 * Цель сдвигает норму: сила — на 20% ниже (объём вторичен, интенсивность
 * важнее), выносливость — планка на 10% ниже, потолок на 15% выше.
 * Уровень сдвигает только новичка (0.7 — тот же коэффициент, что в
 * генераторе): иначе анализ ругает программу, которую сам же построил.
 * Продвинутый норму не поднимает — она остаётся порогом «мало/не мало».
 */
export function volumeNorm(group: string, goal?: string | null,
                           level?: string | null): { lo: number; hi: number } {
  const base = BASE_VOLUME_NORMS[group] || [6, 12];
  let lo = base[0];
  let hi = base[1];
  const g = normalizeGoal(goal);
  if (g === GOALS.STRENGTH) {
    lo = Math.max(2, Math.round(lo * 0.8));
    hi = Math.max(4, Math.round(hi * 0.8));
  } else if (g === GOALS.ENDURANCE) {
    lo = Math.max(2, Math.round(lo * 0.9));
    hi = Math.round(hi * 1.15);
  }
  if (level === 'beginner') {
    lo = Math.max(2, Math.round(lo * 0.7));
    hi = Math.max(4, Math.round(hi * 0.7));
  }
  // Продвинутый уровень норму не поднимает: верхний объём и так выше, а
  // поднятая нижняя граница делала 2-дневные планы невыполнимыми (12 подходов
  // на спину при одном слоте в день). Генератор всё равно целится выше —
  // уровень влияет на цель, а норма остаётся порогом «мало/не мало».
  return { lo, hi };
}
